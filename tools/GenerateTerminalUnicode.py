"""Generate terminal cell-width ranges from Python's pinned Unicode database."""
from pathlib import Path
import unicodedata

if unicodedata.unidata_version != "16.0.0":
    raise SystemExit("Generation requires Unicode 16.0.0 (Python 3.14)")


def ranges(predicate):
    result = []
    first = None
    for value in range(0x110001):
        matches = value < 0x110000 and predicate(chr(value))
        if matches and first is None:
            first = value
        elif not matches and first is not None:
            result.append((first, value - 1))
            first = None
    return result


zero = ranges(lambda c: unicodedata.category(c) in {"Mn", "Mc", "Me", "Cf"})
wide = ranges(lambda c: unicodedata.category(c) != "Cn" and unicodedata.east_asian_width(c) in {"W", "F"})
text = """#pragma once
#include <array>

/** Unicode 16.0.0 cell widths, generated by tools/GenerateTerminalUnicode.py.
 * Data: https://www.unicode.org/ucd/; see UnicodeDataLicense.txt.
 * Ambiguous-width characters occupy one cell. Grapheme joining belongs to the grid.
 */
class TerminalUnicode
{
public:
    static int width(char32_t scalar)
    {
        if (scalar < 32 || (scalar >= 0x7f && scalar < 0xa0) || _contains(_zero, scalar))
        {
            return 0;
        }
        return _contains(_wide, scalar) ? 2 : 1;
    }
private:
    struct Range { char32_t first; char32_t last; };
    template <size_t N> static bool _contains(const std::array<Range, N>& ranges, char32_t scalar)
    {
        size_t begin = 0;
        size_t end = N;
        while (begin < end)
        {
            const size_t middle = begin + (end - begin) / 2;
            if (scalar < ranges[middle].first) { end = middle; }
            else if (scalar > ranges[middle].last) { begin = middle + 1; }
            else { return true; }
        }
        return false;
    }
"""
for name, entries in [("zero", zero), ("wide", wide)]:
    text += f"    static constexpr std::array<Range, {len(entries)}> _{name} {{{{\n"
    text += "".join(f"        {{0x{first:x}, 0x{last:x}}},\n" for first, last in entries)
    text += "    }};\n"
text += "};\n"
root = Path(__file__).resolve().parents[1]
(root / "src/core/src/terminal/TerminalUnicode.h").write_text(text, encoding="utf-8")
print(f"Generated {len(zero)} zero-width and {len(wide)} wide ranges")
